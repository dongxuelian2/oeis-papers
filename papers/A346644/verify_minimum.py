#!/usr/bin/env python3
"""Independent exhaustive controls for the all-index A346644 theorem."""
from math import gcd, prod
from pathlib import Path

from minimum import (elementary_witness, factor, least, normalize,
                     triangular_candidates)
from verify import denominator_from_factors


PUBLISHED = [1, 2, 4, 8, 16, 450, 64, 128, 36, 162, 1024, 1800,
             4096, 1458, 144, 32768, 65536, 54450, 262144, 405000,
             576, 118098, 4194304, 28800, 1296, 1062882, 900,
             5832, 268435456, 115200, 1073741824, 2147483648,
             9216, 86093442, 5184, 217800, 68719476736,
             774840978, 102400]


def integer(fs):
    return prod(p**e for p, e in fs)


def audit():
    # Actual divisor sums/counts avoid the prime-power formula entirely.
    bound = 1000000
    sums, counts = [0]*(bound+1), [0]*(bound+1)
    for d in range(1, bound+1):
        for k in range(d, bound+1, d):
            sums[k] += d
            counts[k] += 1
    minima = {}
    for k in range(1, bound+1):
        den = counts[k]//gcd(sums[k], counts[k])
        minima.setdefault(den, k)
        if k <= 50000:
            result = normalize(factor(k))
            reduced = integer(result)
            assert k % reduced == 0
            assert denominator_from_factors(result) == den
            for p, e in result:
                assert gcd(e+1, (p**(e+1)-1)//(p-1)) == 1
                assert all(den % q == 0 for q, _ in factor(e+1))
    print('PASS divisor-preserving normalization for every K=1..50000', flush=True)

    for n, expected in minima.items():
        actual = least(n)
        assert actual == expected, (n, actual, expected)
    print(f'PASS all {len(minima)} denominator minima occurring at K<=1000000 '
          'against an independent divisor sieve', flush=True)

    for n, expected in enumerate(PUBLISHED, 1):
        assert least(n) == expected, n
        ps = tuple(p for p, _ in factor(expected))
        generated = list(triangular_candidates(n, ps, expected))
        assert any(integer(fs) == expected for fs in generated), n
        assert all(denominator_from_factors(fs) == n for fs in generated)
    print('PASS all 39 published terms, also generated by independent triangular allocations', flush=True)

    # The finite formula must include every normalized factorization, not
    # only the winning one. Compare full sets, using a separate enumeration.
    bound, pool = 20000, (2, 3, 5, 7, 11)
    reference = {}
    for k in range(1, bound+1):
        fs = factor(k)
        if not all(p in pool for p, _ in fs):
            continue
        n = denominator_from_factors(fs)
        if n > 30:
            continue
        if all(gcd(e+1, (p**(e+1)-1)//(p-1)) == 1
               and all(n % q == 0 for q, _ in factor(e+1)) for p, e in fs):
            reference.setdefault(n, set()).add(k)
    total = 0
    for n in range(1, 31):
        produced = {integer(fs) for fs in triangular_candidates(n, pool, bound)}
        assert produced == reference.get(n, set()), (n, produced ^ reference.get(n, set()))
        total += len(produced)
    print(f'PASS complete triangular candidate sets for n<=30, K<=20000 '
          f'over primes {pool}: {total} distinct candidates', flush=True)

    for n in range(1, 201):
        value, fs = elementary_witness(n)
        assert integer(fs) == value and denominator_from_factors(fs) == n
    print('PASS 200 elementary all-index witnesses, with no prime-progressions theorem', flush=True)

    rows = [tuple(map(int, line.split())) for line in
            Path(__file__).with_name('b346644.txt').read_text().splitlines()
            if line and not line.startswith('#')]
    assert [n for n, _ in rows] == list(range(1, 201))
    for n, expected in rows:
        assert least(n) == expected, n
    print('PASS reproducibility of the shipped 200-term table', flush=True)


if __name__ == '__main__':
    audit()
